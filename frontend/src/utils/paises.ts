/** Solo los nombres, en orden alfabético, para las listas de sugerencias. */
export const NOMBRES_PAISES: string[] = PAISES.map((pais) => pais.nombre)

/** Quita tildes, mayúsculas y espacios de los extremos para comparar («Perú» y « peru» son iguales). */
export function normalizarTexto(texto: string): string {
  return texto
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .trim()
}

/** Nacionalidad sugerida para un país de la lista, o `undefined` si el texto no es un país conocido. */
export function nacionalidadDePais(nombre: string): string | undefined {
  const buscado = normalizarTexto(nombre)
  return PAISES.find((pais) => normalizarTexto(pais.nombre) === buscado)?.nacionalidad
}

/** `true` si el nombre del país empieza por lo que se escribió (sin importar tildes ni mayúsculas). */
export function empiezaPor(nombre: string, busqueda: string): boolean {
  return normalizarTexto(nombre).startsWith(normalizarTexto(busqueda))
}
